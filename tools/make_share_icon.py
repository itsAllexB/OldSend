# make_share_icon.py <shapes.png> <out header> [preview.png]
#
# The share-sheet button for OldSend's activity: the logo's shapes (a centre circle ringed by
# eight bars) as a mask. iOS 6 draws an activity image as a mask, so only alpha matters.
# <shapes.png> is either a flat image with coloured shapes on white (art/share-shapes.png,
# LocalSend's logo, which cuts out cleanly) or the glossy app icon, whose light, low-saturation
# shapes are cut out and clipped to a circle so the gloss along its top edge stays out. The mask
# is smoothed, cropped to the logo and scaled to 43 px (1x) and 86 px (@2x). The PNGs are
# written as C arrays, so the share add-on needs no files of its own inside apps that may not be
# allowed to read them.
import io
import sys

from PIL import Image, ImageChops, ImageDraw, ImageFilter

FILL = 0.94  # the logo's share of the button's width


def logo_mask(source_path):
    image = Image.open(source_path).convert('RGB')
    corner = image.getpixel((0, 0))
    if min(corner) > 230:
        # Flat artwork on white: the shapes are whatever isn't white.
        red, _, _ = image.split()
        mask = red.point(lambda x: 255 - x).point(lambda x: 255 if x > 100 else 0)
        return mask.crop(mask.getbbox())
    icon = image
    size = icon.size[0]
    _, saturation, value = icon.convert('HSV').split()
    light = saturation.point(lambda x: 255 if x < 70 else 0)
    bright = value.point(lambda x: 255 if x > 170 else 0)
    mask = ImageChops.multiply(light, bright)
    # Only the logo: a circle around the centre (the bars end at ~40% of the size).
    clip = Image.new('L', icon.size, 0)
    radius = size * 0.45
    ImageDraw.Draw(clip).ellipse([size / 2 - radius, size / 2 - radius,
                                  size / 2 + radius, size / 2 + radius], fill=255)
    mask = ImageChops.multiply(mask, clip)
    # Close small holes, then open away specks, so the edges are clean.
    mask = mask.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.MinFilter(5))
    mask = mask.filter(ImageFilter.MinFilter(5)).filter(ImageFilter.MaxFilter(5))
    return mask.crop(mask.getbbox())


def button(mask, px):
    side = max(mask.size)
    square = Image.new('L', (side, side), 0)
    square.paste(mask, ((side - mask.size[0]) // 2, (side - mask.size[1]) // 2))
    inner = max(1, round(px * FILL))
    shape = square.resize((inner * 8, inner * 8), Image.LANCZOS).resize((inner, inner), Image.LANCZOS)
    alpha = Image.new('L', (px, px), 0)
    alpha.paste(shape, ((px - inner) // 2, (px - inner) // 2))
    out = Image.new('RGBA', (px, px), (0, 0, 0, 0))
    out.putalpha(alpha)
    buf = io.BytesIO()
    out.save(buf, 'PNG', optimize=True)
    return buf.getvalue(), out


def c_array(name, data):
    rows = [', '.join('0x%02x' % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return 'static const unsigned char %s[%d] = {\n    %s\n};\n' % (name, len(data), ',\n    '.join(rows))


def main(source_path, header_path, preview_path=None):
    mask = logo_mask(source_path)
    one, _ = button(mask, 43)
    two, preview = button(mask, 86)
    with open(header_path, 'w', newline='\n') as f:
        f.write('/* Generated by tools/make_share_icon.py from the app icon: the share-sheet button, '
                '43 px and @2x 86 px PNGs (alpha mask). */\n')
        f.write(c_array('kOSShareIcon1x', one))
        f.write(c_array('kOSShareIcon2x', two))
    if preview_path:
        preview.save(preview_path)


if __name__ == '__main__':
    main(*sys.argv[1:4])

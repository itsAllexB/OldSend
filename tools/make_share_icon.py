# make_share_icon.py <out header>: the OldSend logo (a dot ringed by eight dots, as on the app icon)
# as share-sheet activity images. iOS 6 draws an activity image as a mask, so only alpha matters.
# Writes the PNGs (1x 43 px, @2x 86 px) as C arrays, so the share add-on needs no files of its
# own inside apps that may not be allowed to read them.
import io
import math
import sys

from PIL import Image, ImageDraw

SS = 8


def logo(px):
    S = px * SS
    im = Image.new('L', (S, S), 0)
    d = ImageDraw.Draw(im)
    unit = S * 0.47 / 26.0   # outer edge of the ring (20 + 6 units) at 47% of the size
    cx = cy = S / 2.0
    r = 11.6 * unit
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=255)
    for i in range(8):
        a = math.pi * 2 * i / 8
        x, y = cx + 20 * unit * math.cos(a), cy + 20 * unit * math.sin(a)
        d.ellipse([x - 6 * unit, y - 6 * unit, x + 6 * unit, y + 6 * unit], fill=255)
    mask = im.resize((px, px), Image.LANCZOS)
    out = Image.new('RGBA', (px, px), (0, 0, 0, 0))
    out.putalpha(mask)
    buf = io.BytesIO()
    out.save(buf, 'PNG', optimize=True)
    return buf.getvalue()


def c_array(name, data):
    rows = [', '.join('0x%02x' % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return 'static const unsigned char %s[%d] = {\n    %s\n};\n' % (name, len(data), ',\n    '.join(rows))


with open(sys.argv[1], 'w', newline='\n') as f:
    f.write('/* Generated by tools/make_share_icon.py: the share-sheet icon, 43 px and @2x 86 px PNGs. */\n')
    f.write(c_array('kOSShareIcon1x', logo(43)))
    f.write(c_array('kOSShareIcon2x', logo(86)))
